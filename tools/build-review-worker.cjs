// Bundle existing offline parsers for a local Blob worker in mobile file: URLs.
// The wrapper only stores source text; user code is never executed or evaluated.
const fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..');
function build() {
  const entry = fs.readFileSync(path.join(root, 'review-worker.js'), 'utf8');
  const imports = entry.match(/importScripts\(([^)]+)\);/);
  if (!imports) throw new Error('Missing worker dependencies');
  const files = [...imports[1].matchAll(/'([^']+)'/g)].map(match => match[1]);
  const source = entry.replace(imports[0], () => files.map(file => fs.readFileSync(path.join(root, file), 'utf8')).join('\n;\n'));
  new (require('node:vm').Script)(source, { filename: 'native-review-worker.js' });
  return '/* Generated by tools/build-review-worker.cjs; do not edit. */\nwindow.__reviewWorkerSource = ' + JSON.stringify(source) + ';\n';
}
module.exports = { build };
if (require.main === module) {
  const file = path.join(root, 'review-worker-bundle.js'), source = build();
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(file, 'utf8') !== source) throw new Error('Stale native review worker bundle');
    console.log('PASS native review worker matches all parser/checker sources');
  } else { fs.writeFileSync(file, source); console.log('Built native review worker: ' + Buffer.byteLength(source) + ' bytes'); }
}
